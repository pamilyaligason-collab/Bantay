import 'fake-indexeddb/auto'
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { db } from '../../db'
import { hdb } from '../records/store'

const m = vi.hoisted(() => ({ logReading: vi.fn(async () => 1), logMedTaken: vi.fn(async () => 1), logActivity: vi.fn(async () => 1), ask: vi.fn(), addTask: vi.fn(async () => undefined), track: vi.fn(async (_kind: string, _name: string) => true) }))
vi.mock('../admin/events', () => ({ track: m.track }))
vi.mock('../family/tasks', () => ({ addTask: m.addTask }))
vi.mock('../log/store', () => ({ logReading: m.logReading, logMedTaken: m.logMedTaken, logActivity: m.logActivity }))
vi.mock('./client', () => ({ ask: m.ask }))
import Assistant, { ASK_EVENT } from './Assistant'

const draft = { text: 'Draft ready', cards: [{ kind: 'draft', id: 'c0', tool: 'log_reading', fields: { person: 'Lola', test: 'HbA1c', value: '6.1', unit: '%', takenAt: '' } }] }

async function askOnce() {
  render(<Assistant />)
  act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
  fireEvent.change(await screen.findByLabelText('Your question'), { target: { value: 'my sugar was 6.1' } })
  fireEvent.click(screen.getByRole('button', { name: 'Send' }))
  await screen.findByRole('group', { name: /Draft/ })
}

beforeEach(async () => {
  vi.clearAllMocks()
  await db.kv.clear()
  await hdb.people.clear()
  await hdb.readings.clear()
  await hdb.people.add({ id: 'p1', name: 'Lola' })
  m.ask.mockResolvedValue(draft)
})
afterEach(cleanup)

describe('Assistant', () => {
  it('opens a dialog and Esc closes it', async () => {
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    const dlg = await screen.findByRole('dialog')
    fireEvent.keyDown(dlg, { key: 'Escape' })
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
  })
  it('opening sends the ask screen event once (session 6 lane T)', async () => {
    m.track.mockClear()
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    await screen.findByRole('dialog')
    expect(m.track.mock.calls.filter((c) => c[0] === 'screen')).toEqual([['screen', 'ask']])
  })
  it('Confirm saves exactly once, even on a double tap', async () => {
    await askOnce()
    const b = screen.getByRole('button', { name: 'Confirm' })
    fireEvent.click(b)
    fireEvent.click(b)
    await screen.findByText(/Saved for Lola/)
    expect(m.logReading).toHaveBeenCalledTimes(1)
  })
  it('Discard saves nothing', async () => {
    await askOnce()
    fireEvent.click(screen.getByRole('button', { name: 'Discard' }))
    await screen.findByText('Discarded.')
    expect(m.logReading).not.toHaveBeenCalled()
    expect(m.logMedTaken).not.toHaveBeenCalled()
    expect(m.logActivity).not.toHaveBeenCalled()
  })
  it('unknown person: Pick who, Confirm disabled until chosen', async () => {
    m.ask.mockResolvedValue({ text: 'x', cards: [{ ...draft.cards[0], fields: { ...draft.cards[0]!.fields, person: 'Nobody' } }] })
    await askOnce()
    const b = screen.getByRole('button', { name: 'Confirm' }) as HTMLButtonElement
    expect(b.disabled).toBe(true)
    fireEvent.change(screen.getByRole('combobox'), { target: { value: 'p1' } })
    expect(b.disabled).toBe(false)
    fireEvent.click(b)
    await screen.findByText(/Saved for Lola/)
    expect(m.logReading).toHaveBeenCalledTimes(1)
  })
  it('shows the friendly limit message and does not call the server', async () => {
    await db.kv.put({ key: 'assistant.cap', value: { day: new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Manila' }).format(new Date()), count: 30 } })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    fireEvent.change(await screen.findByLabelText('Your question'), { target: { value: 'hi' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText(/used all of today/)
    expect(m.ask).not.toHaveBeenCalled()
  })
  it('privacy.ai off: says so, makes no call and does not use up a daily question', async () => {
    await db.kv.put({ key: 'privacy.ai', value: false })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    fireEvent.change(await screen.findByLabelText('Your question'), { target: { value: 'hi' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('AI is off. Turn it on in Me, Privacy.')
    expect(m.ask).not.toHaveBeenCalled()
    expect(await db.kv.get('assistant.cap')).toBeUndefined()
  })
})

describe('Assistant v2', () => {
  const open = async () => {
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    await screen.findByRole('dialog')
  }
  it('has a one-line title, a small Close icon and the four chips', async () => {
    await open()
    expect(screen.getByRole('heading', { name: 'Ask Bantay' })).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Close' })).toBeTruthy()
    for (const c of ['Log my BP', 'Did I take my medicine?', 'What does HbA1c mean?', 'Add a task']) expect(screen.getByRole('button', { name: c })).toBeTruthy()
  })
  it('a complete chip asks right away; an incomplete one only fills the box', async () => {
    m.ask.mockResolvedValue({ text: 'It means a 3 month average.', cards: [] })
    await open()
    fireEvent.click(screen.getByRole('button', { name: 'Add a task' }))
    expect((screen.getByLabelText('Your question') as HTMLInputElement).value).toBe('Add a task: ')
    expect(m.ask).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'What does HbA1c mean?' }))
    await screen.findByText('It means a 3 month average.')
    expect(m.ask).toHaveBeenCalledTimes(1)
  })
  it('hides the mic when the browser has no speech recognition', async () => {
    await open()
    expect(screen.queryByRole('button', { name: /Speak/ })).toBeNull()
  })
  it('mic fills the box from what was said', async () => {
    let inst: { onresult: (e: unknown) => void; onend: () => void } | undefined
    ;(window as unknown as Record<string, unknown>).webkitSpeechRecognition = class { lang = ''; interimResults = false; onresult: ((e: unknown) => void) | null = null; onend: (() => void) | null = null; onerror = null; start() { inst = this as never } stop() {} }
    try {
      await open()
      fireEvent.click(screen.getByRole('button', { name: 'Speak' }))
      act(() => inst!.onresult({ results: [[{ transcript: 'what is my last sugar' }]] }))
      expect((screen.getByLabelText('Your question') as HTMLInputElement).value).toBe('what is my last sugar')
      act(() => inst!.onend())
      expect(screen.getByRole('button', { name: 'Speak' })).toBeTruthy()
    } finally { delete (window as unknown as Record<string, unknown>).webkitSpeechRecognition }
  })
  it('task card calls addTask once on a double tap and saves nothing on Discard', async () => {
    m.ask.mockResolvedValue({ text: 'Draft', cards: [{ kind: 'task', id: 'c0', title: 'Buy rice', due: '2026-10-25', assignee: 'Lola' }] })
    await open()
    fireEvent.change(screen.getByLabelText('Your question'), { target: { value: 'add a task buy rice' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    const b = await screen.findByRole('button', { name: 'Confirm' })
    fireEvent.click(b)
    fireEvent.click(b)
    await screen.findByText(/Task added: Buy rice/)
    expect(m.addTask).toHaveBeenCalledTimes(1)
    expect(m.addTask).toHaveBeenCalledWith({ title: 'Buy rice', due: '2026-10-25', assigneePersonId: 'p1' })
  })
  it('records card answers locally from saved readings with a citation', async () => {
    await hdb.readings.add({ personId: 'p1', takenAt: '2026-10-02T04:00:00.000Z', test: 'hba1c', value: 6.8, unit: '%', sourceFileId: 'f', confirmedAt: '2026-10-03T00:00:00Z' })
    m.ask.mockResolvedValue({ text: 'Here you go', cards: [{ kind: 'records', id: 'c0', person: 'Lola', test: 'HbA1c' }] })
    await open()
    fireEvent.change(screen.getByLabelText('Your question'), { target: { value: 'my last hba1c' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText(/last HbA1c was 6.8 %/)
    expect(screen.getByText('From your lab result on 2 Oct 2026')).toBeTruthy()
  })
})

describe('Assistant round 3', () => {
  it('no filler bubble when a card follows, chips collapse, task shows words and whole family', async () => {
    m.ask.mockResolvedValue({ text: '', cards: [{ kind: 'task', id: 'c0', title: 'Buy rice', due: '2026-10-23', assignee: '' }] })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    fireEvent.change(await screen.findByLabelText('Your question'), { target: { value: 'add a task' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('Fri, Oct 23')
    expect(screen.getByText('Whole family')).toBeTruthy()
    expect(screen.queryByText('Here is what I found.')).toBeNull()
    expect(screen.queryByRole('group', { name: 'Suggestions' })).toBeNull()
  })
  it('records card with an unclear person shows chips to pick', async () => {
    await hdb.people.add({ id: 'p2', name: 'Lolita' })
    m.ask.mockResolvedValue({ text: '', cards: [{ kind: 'records', id: 'c0', person: 'Lol', test: 'HbA1c' }] })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    fireEvent.change(await screen.findByLabelText('Your question'), { target: { value: 'hba1c' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('Whose result do you mean?')
    expect(screen.getByRole('button', { name: 'Lolita' })).toBeTruthy()
  })
  it('task card with an unmatched name asks who, never says Whole family on its own', async () => {
    await hdb.people.add({ id: 'p2', name: 'Maria Roc' })
    await hdb.people.add({ id: 'p3', name: 'Rosalino Roc' })
    m.ask.mockResolvedValue({ text: '', cards: [{ kind: 'task', id: 'c0', title: 'Buy rice', due: '', assignee: 'Roc' }] })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    fireEvent.change(await screen.findByLabelText('Your question'), { target: { value: 'task for Roc' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('Who is "Roc"?')
    expect((screen.getByRole('button', { name: 'Confirm' }) as HTMLButtonElement).disabled).toBe(true)
    expect(screen.getAllByRole('button', { name: /Roc$/ })).toHaveLength(2) // matches first, then everyone else
    expect(screen.getByText('Pick who this is for')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Rosalino Roc' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm' }))
    await screen.findByText(/Task added/)
    expect(m.addTask).toHaveBeenCalledWith({ title: 'Buy rice', assigneePersonId: 'p3' })
  })
  it('draft for Lola with only Lolita cannot be confirmed until a person is picked', async () => {
    await hdb.people.clear()
    await hdb.people.add({ id: 'p2', name: 'Lolita' })
    m.ask.mockResolvedValue({ text: '', cards: [{ kind: 'draft', id: 'c0', tool: 'log_med_taken', fields: { person: 'Lol', name: 'Losartan', takenAt: '' } }] })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    fireEvent.change(await screen.findByLabelText('Your question'), { target: { value: 'I took losartan' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('Pick who this is for')
    expect((screen.getByRole('button', { name: 'Confirm' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(screen.getByRole('combobox'), { target: { value: 'p2' } })
    expect((screen.getByRole('button', { name: 'Confirm' }) as HTMLButtonElement).disabled).toBe(false)
  })
  it('records card for Lola with one person Rosalino shows chips, not Rosalino', async () => {
    await hdb.people.clear()
    await hdb.people.add({ id: 'p1', name: 'Rosalino' })
    m.ask.mockResolvedValue({ text: '', cards: [{ kind: 'records', id: 'c0', person: 'Lola', test: 'BP' }] })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    fireEvent.change(await screen.findByLabelText('Your question'), { target: { value: "Lola's BP" } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('Whose result do you mean?')
    expect(screen.getByRole('button', { name: 'Rosalino' })).toBeTruthy()
  })
  it('Whole family chip saves a named-but-unmatched task with no assignee', async () => {
    m.ask.mockResolvedValue({ text: '', cards: [{ kind: 'task', id: 'c0', title: 'Buy rice', due: '', assignee: 'Zed' }] })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    fireEvent.change(await screen.findByLabelText('Your question'), { target: { value: 'task for Zed' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('Who is "Zed"?')
    fireEvent.click(screen.getByRole('button', { name: 'Whole family' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm' }))
    await screen.findByText(/Task added/)
    expect(m.addTask).toHaveBeenCalledWith({ title: 'Buy rice' })
  })
  it('shows the new caution line, not "I can mix things up"', async () => {
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    await screen.findByRole('dialog')
    expect(screen.getByText(/I can be wrong\. Check with your doctor for medical decisions\./)).toBeTruthy()
    expect(screen.queryByText(/mix things up/)).toBeNull()
  })
  it('brings back only the last 20 messages from this phone', async () => {
    const old = Array.from({ length: 25 }, (_, i) => ({ role: i % 2 ? 'assistant' : 'user', content: `old message ${i}` }))
    await db.kv.put({ key: 'assistant.history', value: old })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    await screen.findByText('old message 24')
    expect(screen.getByText('old message 5')).toBeTruthy()
    expect(screen.queryByText('old message 4')).toBeNull()
  })
  it('keeps the chat on the device after a reply, 20 at most, without cards', async () => {
    const old = Array.from({ length: 20 }, (_, i) => ({ role: i % 2 ? 'assistant' : 'user', content: `m${i}` }))
    await db.kv.put({ key: 'assistant.history', value: old })
    m.ask.mockResolvedValue({ text: 'It means a 3 month sugar average.', cards: [{ kind: 'weather', id: 'c0' }] })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    await screen.findByText('m19')
    fireEvent.change(screen.getByLabelText('Your question'), { target: { value: 'what is hba1c' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('It means a 3 month sugar average.')
    await waitFor(async () => {
      const kept = (await db.kv.get('assistant.history'))?.value as { content: string; cards?: unknown }[]
      expect(kept).toHaveLength(20)
      expect(kept[19]).toEqual({ role: 'assistant', content: 'It means a 3 month sugar average.' })
      expect(kept[0]!.content).toBe('m2')
    })
  })
  it('Clear chat empties the list and removes the saved history', async () => {
    await db.kv.put({ key: 'assistant.history', value: [{ role: 'user', content: 'private question' }] })
    render(<Assistant />)
    act(() => { window.dispatchEvent(new Event(ASK_EVENT)) })
    await screen.findByText('private question')
    fireEvent.click(screen.getByRole('button', { name: 'Clear chat' }))
    await waitFor(() => expect(screen.queryByText('private question')).toBeNull())
    await waitFor(async () => expect(await db.kv.get('assistant.history')).toBeUndefined())
    expect(screen.queryByRole('button', { name: 'Clear chat' })).toBeNull()
  })
})
