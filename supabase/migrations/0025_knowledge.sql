create table if not exists public.knowledge_topics (
  slug text primary key check (slug ~ '^[a-z0-9-]{2,60}$'),
  title_en text not null check (char_length(title_en) between 1 and 120),
  title_tl text not null check (char_length(title_tl) between 1 and 120),
  summary text not null check (char_length(summary) between 40 and 700),
  source_name text not null check (char_length(source_name) between 2 and 40),
  source_url text not null check (source_url ~ '^https://'),
  reviewed_at date not null,
  fts tsvector generated always as (
    setweight(to_tsvector('english', title_en), 'A') || setweight(to_tsvector('english', summary), 'B')
  ) stored
);
create index if not exists knowledge_topics_fts on public.knowledge_topics using gin (fts);

-- A word or phrase someone might type (English, Tagalog or Taglish) that points at a topic. Lower case letters, digits, spaces, apostrophes and hyphens only,
-- so search_knowledge can use a term inside a regular expression without escaping it.
create table if not exists public.knowledge_synonyms (
  term text not null check (term = lower(term) and term ~ '^[a-z0-9][a-z0-9 ''-]{0,59}$'),
  topic_slug text not null references public.knowledge_topics (slug) on update cascade on delete cascade,
  primary key (term, topic_slug)
);
create index if not exists knowledge_synonyms_topic on public.knowledge_synonyms (topic_slug);

do $$ declare t text; begin
  foreach t in array array['knowledge_topics', 'knowledge_synonyms'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
    execute format('drop policy if exists %I on public.%I', t || '_read', t);
    execute format('create policy %I on public.%I for select to authenticated using (true)', t || '_read', t);
  end loop;
end $$;

-- Best topics for a question: a synonym found in the question counts most, English full-text matches (any word, ranked) add to it.
-- The question is cut to 200 characters; an empty or null question returns no rows; max_rows is held between 1 and 10.
create or replace function public.search_knowledge(q text, max_rows integer default 5)
returns table (slug text, title_en text, title_tl text, summary text, source_name text, source_url text, reviewed_at date, rank real)
language sql stable security invoker set search_path = '' as $$
  with args as (
    select lower(left(btrim(coalesce(q, '')), 200)) as s,
           replace(websearch_to_tsquery('english', left(coalesce(q, ''), 200))::text, ' & ', ' | ')::tsquery as tq
  ), hits as (
    select y.topic_slug, count(*)::real as n
      from public.knowledge_synonyms y, args
     where args.s ~ ('\m' || y.term || '\M')
     group by y.topic_slug
  )
  select t.slug, t.title_en, t.title_tl, t.summary, t.source_name, t.source_url, t.reviewed_at,
         (coalesce(h.n, 0) + case when t.fts @@ args.tq then ts_rank(t.fts, args.tq) else 0 end)::real as rank
    from public.knowledge_topics t
    cross join args
    left join hits h on h.topic_slug = t.slug
   where h.n is not null or (t.fts @@ args.tq and ts_rank(t.fts, args.tq) > 0)
   order by 8 desc, t.slug
   limit greatest(1, least(coalesce(max_rows, 5), 10))
$$;
revoke all on function public.search_knowledge(text, integer) from public, anon;
grant execute on function public.search_knowledge(text, integer) to authenticated;

